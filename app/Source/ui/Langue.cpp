Langue::Choix Langue::courante() { return etatCourant(); }

int Langue::tailleDeLaTable() { return kNombreDePaires; }

juce::String Langue::libelle(Choix choix) {
    // CHAQUE LANGUE DANS LA SIENNE : c'est la convention de tous les sélecteurs
    // de langue, et la seule qui permette à quelqu'un de retrouver la sienne
    // quand l'interface est posée dans une langue qu'il ne lit pas.
    return choix == Choix::Anglais ? juce::String("English")
                                   : juce::String::fromUTF8("Français");
}

bool Langue::appliquer(Choix choix) {
    const bool change = choix != etatCourant();
    etatCourant() = choix;
    poserLaTable(choix);
    UiScale::properties().setValue(kCleReglage, choix == Choix::Anglais ? "en" : "fr");
    UiScale::properties().saveIfNeeded();
    return change;
}

void Langue::appliquerAuDemarrage() {
    Choix choix = depuisLeTexte(UiScale::properties().getValue(kCleReglage, "fr"),
                                Choix::Francais);
    // VSM_LANGUE L'EMPORTE, SANS ÉCRASER LE RÉGLAGE. Un banc choisit sa langue
    // pour une course ; il ne doit pas changer ce que l'utilisateur a réglé,
    // sans quoi une vérification en anglais laisserait le DAW en anglais.
    if (const char* force = std::getenv("VSM_LANGUE"); force != nullptr && *force) {
        etatCourant() = depuisLeTexte(juce::String::fromUTF8(force), choix);
        poserLaTable(etatCourant());
        return;
    }
    etatCourant() = choix;
    poserLaTable(choix);
}

juce::String tr(const char* texte) {
    // `fromUTF8` ET NON `juce::String(const char*)` : le second lit les octets
    // en Latin-1 et rend « s'éclaircit » en « s'Â©claircit ». Passer par la
    // traduction devient donc aussi la façon sûre d'écrire un accent.
    return juce::translate(juce::String::fromUTF8(texte));
}

juce::String tr(const char8_t* texte) {
    return juce::translate(juce::String::fromUTF8(reinterpret_cast<const char*>(texte)));
}

juce::String tr(const juce::String& texte) { return juce::translate(texte); }

juce::String trSelon(const char* contexte, const char8_t* texte) {
    const juce::String seul = tr(texte);
    if (juce::LocalisedStrings::getCurrentMappings() == nullptr) return seul;
    const juce::String cle = juce::String::fromUTF8(reinterpret_cast<const char*>(texte))
                             + "@" + juce::String(contexte);
    const juce::String traduit = juce::translate(cle);
    return traduit != cle ? traduit : seul;
}

juce::String trGeste(const juce::String& libelle) {
    // LES NOMS FABRIQUÉS se reconnaissent à leur modèle : un préfixe fixe, puis
    // une donnée -- « Signature 3/4 » (D82), « Durée x1.50 » et « Vélocité
    // x0.80 » (D94, les gestes du piano roll). Les autres sont des clés.
    for (const char8_t* modele : { u8"Signature %1", u8"Durée x%1", u8"Vélocité x%1" }) {
        const juce::String m = juce::String::fromUTF8(reinterpret_cast<const char*>(modele));
        const juce::String prefixe = m.upToFirstOccurrenceOf("%1", false, false);
        if (libelle.startsWith(prefixe))
            return tr(m).replace("%1", libelle.substring(prefixe.length()));
    }
    return tr(libelle);
}

